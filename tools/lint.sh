#!/usr/bin/env bash
# Static checks for fenix-police: luacheck against the real FiveM native lists.
#
#   tools/lint.sh                  lint every Lua file in the resource
#   tools/lint.sh FILE...          lint only these files
#   tools/lint.sh --no-color ...   luacheck options pass straight through
#
# Needs: luacheck (`luarocks install luacheck`), npm, tar, and luac5.4 for the
# compile check.
#
# The native lists are generated once into .luacheck/ (gitignored) from the
# @citizenfx/client and @citizenfx/server npm typings. Pinned, so a lint run
# today and one in a year agree on what a native is. Delete .luacheck/ or bump
# CFX_TYPINGS_VERSION to regenerate.
set -euo pipefail

cd "$(dirname "$0")/.."

CFX_TYPINGS_VERSION="${CFX_TYPINGS_VERSION:-2.0.37175-1}"
OUT=.luacheck

gen_natives() {
    local side=$1 dir=$2
    {
        echo "-- Generated by tools/lint.sh from @citizenfx/$side@$CFX_TYPINGS_VERSION. Do not edit."
        echo 'return {'
        grep -ohE 'declare function [A-Za-z_][A-Za-z0-9_]*' "$dir"/package/*.d.ts \
            | awk '{ print "    \"" $3 "\"," }' | sort -u
        echo '}'
    } > "$OUT/natives_$side.lua"
}

if [[ ! -s $OUT/natives_client.lua || ! -s $OUT/natives_server.lua ]]; then
    command -v npm >/dev/null || { echo 'lint: npm is required to fetch the FiveM native typings' >&2; exit 2; }
    mkdir -p "$OUT"
    tmp=$(mktemp -d)
    trap 'rm -rf "$tmp"' EXIT
    for side in client server; do
        mkdir -p "$tmp/$side"
        tarball=$(cd "$tmp/$side" && npm pack --silent "@citizenfx/$side@$CFX_TYPINGS_VERSION")
        tar -xzf "$tmp/$side/$tarball" -C "$tmp/$side"
        gen_natives "$side" "$tmp/$side"
    done
fi

opts=() files=()
for arg in "$@"; do
    if [[ $arg == -* ]]; then opts+=("$arg"); else files+=("$arg"); fi
done
if [[ ${#files[@]} -eq 0 ]]; then
    mapfile -t files < <(git ls-files '*.lua')
fi

# luacheck parses but never compiles, so it can't see a compiler limit: the
# 200 locals a function may have in scope at once, which client.lua's top
# level once crossed with luacheck still reporting it clean. FiveM's runtime
# is Lua 5.4 (lua54 'yes' in both manifests), so compile with 5.4.
status=0
luac=$(command -v luac5.4 || true)
if [[ -z $luac ]] && command -v luac >/dev/null && luac -v 2>&1 | grep -q 'Lua 5\.4'; then
    luac=$(command -v luac)
fi
if [[ -n $luac ]]; then
    for f in "${files[@]}"; do
        "$luac" -p "$f" || status=1
    done
else
    echo 'lint: luac5.4 not found, skipping the compile check' >&2
fi

luacheck "${opts[@]}" "${files[@]}" || status=$?
exit "$status"
